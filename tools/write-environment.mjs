// Writes apps/aura/src/environments/environment.prod.ts from the build's environment variables,
// so the hosting build (Cloudflare Pages) talks to the hosted Supabase project:
//
//   AURA_SUPABASE_URL       https://<project>.supabase.co
//   AURA_SUPABASE_ANON_KEY  the project's anon (publishable) key; public by design
//   AURA_LOGIN_DOMAIN       optional, defaults to login.aura.invalid; must match the edge functions
//
// Never put the service-role key here: it belongs only in Supabase function secrets.
import { writeFileSync } from 'node:fs';

const url = process.env.AURA_SUPABASE_URL;
const anonKey = process.env.AURA_SUPABASE_ANON_KEY;
const loginDomain = process.env.AURA_LOGIN_DOMAIN || 'login.aura.invalid';
if (!url || !anonKey) {
  console.error('Set AURA_SUPABASE_URL and AURA_SUPABASE_ANON_KEY.');
  process.exit(1);
}
const backend = { kind: 'supabase', url, anonKey, loginDomain, clubManifests: true };
writeFileSync(
  new URL('../apps/aura/src/environments/environment.prod.ts', import.meta.url),
  `// Generated by tools/write-environment.mjs for this build.\n` +
    `import { AppEnvironment } from './app-environment';\n\n` +
    `export const environment: AppEnvironment = { backend: ${JSON.stringify(backend)} };\n`,
);
console.log(`Production build will use ${url}`);
